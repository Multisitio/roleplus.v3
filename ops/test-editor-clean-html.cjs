const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');
// Run with jsdom available on NODE_PATH.
(async () => {
  const dom = new JSDOM('<main><div contenteditable="true" data-idu="page"><article><section><div class="">&#8203;</div><p class="keep">Texto<b>&amp;ZeroWidthSpace;</b></p></section></article></div></main>', {runScripts:'outside-only', url:'https://example.test/editor'});
  const w = dom.window;
  let saved;
  w.fetch = async (url, options) => { saved = options.body.get('descripcion'); return {ok:true,status:200,json:async()=>({success:true})}; };
  const source = fs.readFileSync('web/javascript/editor/5-pinceles.js','utf8');
  w.eval(source.replace('})(window, document);', 'window.testEditor = {syncHelpers,placeCursorInside,insertTag,saveArticle,clearActiveHelpers,activate:el=>activeArticle=el}; })(window, document);'));
  const api = w.testEditor;
  const page = w.document.querySelector('[contenteditable]');
  const container = page.querySelector('section > div');
  const clean = () => {
    assert.doesNotMatch(page.innerHTML, /\u200B|ZeroWidthSpace|class="\s*"/i);
    assert.equal(page.querySelector('.keep').textContent, 'Texto');
  };
  api.activate(page);
  api.syncHelpers(page);
  clean();
  api.placeCursorInside(container);
  api.insertTag({tag:'h4',block:true,wrap:false,children:''});
  clean();
  const heading = container.querySelector('h4');
  assert.ok(heading);
  assert.equal(w.getSelection().anchorNode, heading);
  const range = w.getSelection().getRangeAt(0);
  const text = w.document.createTextNode('Titulo');
  range.insertNode(text);
  range.setStart(text,text.length);
  range.collapse(true);
  api.syncHelpers(page);
  assert.equal(w.getSelection().anchorNode,text);
  assert.equal(w.getSelection().anchorOffset,6);
  assert.equal(heading.querySelector('[data-editor-helper]'),null);
  heading.classList.add('is-active-helper');
  api.clearActiveHelpers();
  clean();
  heading.classList.add('is-active-helper');
  assert.equal(await api.saveArticle(page),true);
  assert.equal(saved,'<article><section><div><h4>Titulo</h4></div><p class="keep">Texto<b></b></p></section></article>');
  heading.textContent='';
  api.syncHelpers(page);
  api.placeCursorInside(heading);
  clean();
  assert.equal(w.getSelection().anchorNode,heading);
  assert.equal(await api.saveArticle(page),true);
  assert.match(saved,/<h4><\/h4>/);
  assert.doesNotMatch(saved,/data-editor-helper|is-active-helper|data-empty-helper|\u200B|class=""/);
  dom.window.close();
  console.log('PASS: nested H4, legacy cleanup, cursor, empty heading, real classes and saved HTML');
})().catch(e=>{console.error(e);process.exit(1);});
